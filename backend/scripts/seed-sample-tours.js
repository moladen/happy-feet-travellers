async function main() {
  console.log('🌱 Upserting sample tours (no wipe)...');
  let count = 0;
  for (const tour of sampleTours) {
    const slug = tour.slug || slugify(tour.title);
    const { slug: _s, ...data } = tour;
    await prisma.tour.upsert({
      where: { slug },
      create: { ...data, slug },
      update: { ...data, slug },
    });
    console.log(`  ✓ ${tour.category === 'upcoming' ? 'Upcoming' : 'Personalized'}: ${tour.title}`);
    count += 1;
  }
  console.log(`✅ Done — ${count} tours upserted.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
